/**
 * PDF Report Generator for AuraHire
 * Uses jsPDF loaded via CDN
 */

export async function generatePDF(sessionData) {
  if (typeof window === 'undefined' || !window.jspdf) {
    console.warn("jsPDF not loaded yet");
    return false;
  }

  const { jsPDF } = window.jspdf;
  const doc = new jsPDF();
  const purple = '#534AB7';
  const text = '#1A1A18';
  const muted = '#6B6B68';

  // --- Page 1: Cover ---
  // Top Header Rect
  doc.setFillColor(purple);
  doc.rect(0, 0, 210, 20, 'F');

  // App Name
  doc.setFont("helvetica", "bold");
  doc.setFontSize(28);
  doc.setTextColor(purple);
  doc.text("Aura", 20, 45);
  doc.setTextColor(text);
  doc.text("Hire", 42, 45);

  // Tagline
  doc.setFontSize(12);
  doc.setFont("helvetica", "normal");
  doc.setTextColor(muted);
  doc.text("Your vibe, perfected by AI", 20, 52);

  // Date
  const dateStr = new Date(sessionData.date).toLocaleDateString('en-US', {
    day: 'numeric', month: 'long', year: 'numeric'
  });
  doc.setFontSize(10);
  doc.text(`Session Date: ${dateStr}`, 140, 45);

  // Large Aura Score Circle
  doc.setLineWidth(1.5);
  doc.setDrawColor(purple);
  doc.circle(105, 110, 30, 'S');
  
  doc.setFontSize(48);
  doc.setTextColor(purple);
  doc.setFont("helvetica", "bold");
  const scoreText = sessionData.auraScore.toString();
  const scoreX = 105 - (doc.getTextWidth(scoreText) / 2);
  doc.text(scoreText, scoreX, 115);

  doc.setFontSize(16);
  doc.setTextColor(text);
  doc.text("Aura Score", 88, 145);

  // --- Page 2: Metrics ---
  doc.addPage();
  
  doc.setFontSize(20);
  doc.setTextColor(purple);
  doc.text("Session Breakdown", 20, 30);
  
  doc.setDrawColor(230, 230, 230);
  doc.line(20, 35, 190, 35);
  
  const metrics = [
    { label: "Confidence", value: `${sessionData.avgConfidence}%` },
    { label: "Engagement", value: `${sessionData.avgEngagement}%` },
    { label: "Stress (inverted)", value: `${100 - sessionData.avgStress}%` },
    { label: "Eye Contact", value: `${sessionData.avgEyeContact}%` },
    { label: "Speaking Pace", value: `${sessionData.avgWPM} WPM` },
    { label: "Filler Words", value: sessionData.fillerCount.toString() },
  ];

  let y = 50;
  metrics.forEach(m => {
    doc.setFont("helvetica", "normal");
    doc.setFontSize(12);
    doc.setTextColor(text);
    doc.text(m.label, 20, y);
    
    doc.setFont("helvetica", "bold");
    doc.text(m.value, 160, y);
    
    doc.setDrawColor(245, 245, 245);
    doc.line(20, y + 4, 190, y + 4);
    y += 15;
  });

  // --- Page 3: Transcript ---
  doc.addPage();
  doc.setFontSize(20);
  doc.setTextColor(purple);
  doc.text("Full Transcript", 20, 30);
  
  doc.setFont("courier", "normal");
  doc.setFontSize(9);
  doc.setTextColor(text);
  
  const transcript = sessionData.transcript || "No transcript available.";
  const splitTranscript = doc.splitTextToSize(transcript, 170);
  doc.text(splitTranscript, 20, 45);

  // --- Page 4: AI Recommendations ---
  doc.addPage();
  doc.setFontSize(20);
  doc.setTextColor(purple);
  doc.text("Top 3 AI Improvements", 20, 30);
  
  const tips = sessionData.tips || [];
  y = 50;
  tips.forEach((tip, i) => {
    doc.setFont("helvetica", "bold");
    doc.setFontSize(14);
    doc.setTextColor(purple);
    doc.text(`${i + 1}.`, 20, y);
    
    doc.setFont("helvetica", "normal");
    doc.setFontSize(12);
    doc.setTextColor(text);
    const splitTip = doc.splitTextToSize(tip, 160);
    doc.text(splitTip, 30, y);
    y += 30;
  });

  // Footer
  const pageCount = doc.internal.getNumberOfPages();
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i);
    doc.setFontSize(9);
    doc.setTextColor(muted);
    doc.text("Generated by AuraHire · aurahire.vercel.app", 105, 285, { align: 'center' });
  }

  const filename = `aurahire-report-${new Date().toISOString().split('T')[0]}.pdf`;
  doc.save(filename);
  return true;
}
